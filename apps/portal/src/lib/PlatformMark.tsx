const PLAIN = { podcast: Mic, website: Globe, newsletter: Mail } as const;

/** What each platform is called, for labels and screen readers. */
export const PLATFORM_NAMES: Record<string, string> = {
  linkedin: 'LinkedIn',
  twitter: 'X',
  youtube: 'YouTube',
  instagram: 'Instagram',
  tiktok: 'TikTok',
  substack: 'Substack',
  twitch: 'Twitch',
  facebook: 'Facebook',
  pinterest: 'Pinterest',
  snapchat: 'Snapchat',
  reddit: 'Reddit',
  threads: 'Threads',
  bluesky: 'Bluesky',
  podcast: 'Podcast',
  website: 'Website',
  newsletter: 'Newsletter',
};

export const platformName = (platform: string) => PLATFORM_NAMES[platform] ?? platform;

/** 6M, 32.9K, 950. */
export function compactCount(n: number): string {
  return new Intl.NumberFormat('en', { notation: 'compact', maximumFractionDigits: 1 }).format(n);
}

/** An engagement rate, which the Network gives in percent: 2.4%, 12%,
 *  <0.1%. */
export function formatRate(rate: number): string {
  if (rate > 0 && rate < 0.05) return '<0.1%';
  return `${new Intl.NumberFormat('en', { maximumFractionDigits: rate < 10 ? 1 : 0 }).format(rate)}%`;
}

/** The rate in full, for a tooltip: "2.41% engagement over 10 posts". */
export function rateInFull(rate: number, posts: number | null | undefined, platform: string): string {
  const over = posts ? ` over ${posts} ${platform === 'youtube' ? 'videos' : 'posts'}` : '';
  return `${rate.toLocaleString('en', { maximumFractionDigits: 2 })}% engagement${over}`;
}

/** The platform's logo, `size` px tall. Named for screen readers only when
 *  nothing beside it names the platform (`label`). */
export function PlatformMark({ platform, size = 14, label }: { platform: string; size?: number; label?: string }) {
  const a11y = label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': true };
  if (platform === 'linkedin') {
    // Wider than tall: the logo carries LinkedIn's registered mark.
    return <img src="/linkedin-in-bug.png" alt={label ?? ''} style={{ height: size, width: 'auto', display: 'block', flexShrink: 0 }} />;
  }
  const mark = MARKS[platform];
  if (!mark) {
    const Icon = PLAIN[platform as keyof typeof PLAIN] ?? Link2;
    return <Icon size={size} {...a11y} style={{ color: theme.textMuted, flexShrink: 0 }} />;
  }
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" {...a11y} style={{ display: 'block', flexShrink: 0 }}>
      {mark.underlay === 'circle' && <circle cx="12" cy="12" r="11" fill="#fff" />}
      {mark.underlay === 'play' && <rect x="9" y="8" width="7.5" height="8" fill="#fff" />}
      <path d={mark.path} fill={mark.color ?? 'currentColor'} />
    </svg>
  );
}

/** One channel: its logo and followers, and its engagement rate when it
 *  has one, linking to the profile when there is one. The full figures are
 *  in the tooltip. */
export function ChannelCount({
  platform,
  followers,
  href,
  verified = false,
  size = 14,
  engagementRate,
  engagementPosts,
}: {
  platform: string;
  followers: number | null;
  href?: string | null;
  verified?: boolean;
  size?: number;
  /** Percent. */
  engagementRate?: number | null;
  /** The posts the rate averages. */
  engagementPosts?: number | null;
}) {
  const name = platformName(platform);
  const full = [
    name,
    ...(followers != null ? [`${followers.toLocaleString()} followers`] : []),
    ...(engagementRate != null ? [rateInFull(engagementRate, engagementPosts, platform)] : []),
    ...(verified ? ['verified'] : []),
  ].join(', ');
  const style: CSSProperties = {
    display: 'inline-flex',
    alignItems: 'center',
    gap: 5,
    fontSize: 13,
    color: theme.text,
    textDecoration: 'none',
    whiteSpace: 'nowrap',
  };
  const body = (
    <>
      <PlatformMark platform={platform} size={size} label={href ? undefined : name} />
      {followers != null && <span>{compactCount(followers)}</span>}
      {engagementRate != null && <span style={{ color: theme.textMuted }}>· {formatRate(engagementRate)}</span>}
      {verified && <VerifiedBadge compact />}
    </>
  );
  return href ? (
    <a href={href} target="_blank" rel="noreferrer noopener" title={full} aria-label={full} style={style}>
      {body}
    </a>
  ) : (
    <span title={full} style={style}>
      {body}
    </span>
  );
}

/** A creator's channels in a row, wrapping. */
export function ChannelCounts({ children, style }: { children: React.ReactNode; style?: CSSProperties }) {
  return <div style={{ display: 'flex', flexWrap: 'wrap', alignItems: 'center', gap: '4px 12px', ...style }}>{children}</div>;
}
